"""The brain's `Responder`, backed by the language model (docs/07 §3.1 `compose`, docs/27 §6).

The last Milestone-4 stub on the reply path. Until this existed no language model received
anything; now every reply is generated by one, from a prompt the assembler built out of who
HEDWIG is, how it should speak, what it remembers and the conversation so far.

This module translates a turn into sections. It does not decide what fits — the assembler
does — and it does not decide what HEDWIG is like — personality and emotion did, upstream,
and their directives arrive already rendered. Each concern has one owner.
"""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass, field
from typing import Protocol

from hedwig.core.errors import CapabilityUnavailableError
from hedwig.core.logging import fields, get_logger
from hedwig.core.ports.brain import (
    Intent,
    Plan,
    ResponseContext,
    SafetyVerdict,
    ToolOutcome,
    TrustTier,
    TurnPolicy,
)
from hedwig.core.ports.llm import GenerationRequest, GenerationResult, Role
from hedwig.core.ports.sessions import WindowMessage
from hedwig.llm.errors import LLMError
from hedwig.llm.prompts import PROMPT_VERSION, SAFETY_MARGIN, Entry, PromptAssembler

logger = get_logger(__name__)

PURPOSE = "compose.reply"
DEFAULT_CONTEXT_WINDOW = 8192

CLARIFY_DIRECTIVE = "The request is ambiguous: ask one short question rather than guessing."

REFUSAL = (
    "I'm not going to help with that. If I've misread what you meant, tell me a bit more and "
    "I'll look at it again."
)
"""Fixed, not generated (docs/27 §6.1). A refusal should not depend on the component most
likely to be down, and should never be phrased by the thing being refused. It names no reason
and quotes nothing, so no part of the refused input is echoed back."""


class Generator(Protocol):
    """The slice of the gateway a responder needs."""

    async def generate(self, request: GenerationRequest) -> GenerationResult: ...


@dataclass(slots=True)
class GatewayResponder:
    """Adapts the language model gateway to the brain's `Responder` port."""

    gateway: Generator
    context_window: int = DEFAULT_CONTEXT_WINDOW
    assembler: PromptAssembler = field(default_factory=PromptAssembler)

    async def compose(
        self,
        *,
        text: str,
        plan: Plan,
        context: ResponseContext,
        policy: TurnPolicy,
    ) -> str:
        """Generate the reply.

        Raises `CapabilityUnavailableError` when there is no model to ask; `compose` turns
        that into an honest reply and a failed turn, rather than an exception the user sees.
        """
        directives = list(context.directives)
        if plan.intent is Intent.CLARIFY:
            directives.insert(0, CLARIFY_DIRECTIVE)

        prompt = self.assembler.assemble(
            budget=max(256, self.context_window - policy.max_tokens - SAFETY_MARGIN),
            user=text,
            identity=context.identity,
            directives=directives,
            memory=[
                Entry(text=item.text, rank=item.score)
                for item in context.recalled
                if item.trust is not TrustTier.UNTRUSTED
            ],
            untrusted=[
                Entry(text=item.text, rank=item.score)
                for item in context.recalled
                if item.trust is TrustTier.UNTRUSTED
            ],
            tools=[Entry(text=_render_outcome(outcome)) for outcome in context.outcomes],
            window=_conversation(context.window, current=text),
        )

        request = GenerationRequest(
            messages=prompt.messages,
            purpose=PURPOSE,
            max_tokens=policy.max_tokens,
            temperature=policy.temperature,
            metadata={
                "prompt_version": prompt.version,
                "prompt_tokens_estimated": prompt.tokens,
                "trimmed": dict(prompt.trimmed),
                "directives": len(directives),
                "intent": plan.intent.value,
            },
        )

        try:
            result = await self.gateway.generate(request)
        except LLMError as error:
            logger.warning("language model unavailable", extra=fields(error=str(error)))
            raise CapabilityUnavailableError(
                "the language model is unavailable", cause="unreachable"
            ) from error

        reply = result.text.strip()
        if not reply:
            # A reasoning model can spend its whole budget thinking and return no answer
            # (docs/14 §13.1). That is a failure to answer, not an empty answer.
            raise CapabilityUnavailableError(
                "the language model returned no reply", cause="no_answer"
            )

        if prompt.trimmed:
            logger.info("prompt trimmed to fit", extra=fields(**prompt.trimmed))
        return reply

    async def refuse(self, *, verdict: SafetyVerdict) -> str:
        return REFUSAL


def _conversation(window: Sequence[WindowMessage], *, current: str) -> list[tuple[Role, str]]:
    """The recent turns as chat messages, without the message being answered.

    The window is read after `ingest` has recorded the current input, so its last entry *is*
    the input. Sending it twice — once in the window, once as the final user message — would
    make the model answer a doubled question.
    """
    turns = [(Role.USER if m.role == "user" else Role.ASSISTANT, m.text) for m in window]
    if turns and turns[-1] == (Role.USER, current):
        turns.pop()
    return turns


def _render_outcome(outcome: ToolOutcome) -> str:
    if outcome.ok:
        return f"{outcome.name}: {outcome.output}"
    return f"{outcome.name} failed: {outcome.error or 'unknown error'}"


